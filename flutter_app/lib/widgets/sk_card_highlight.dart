/// 카드 한 장에 붙는 강조의 뜻.
///
/// 하나의 bool 로 두면 "강조됨" 밖에 말할 수 없어서, 뜻이 다른 세 가지가
/// 같은 모양으로 그려진다. 실제로 그랬다 — 벤트로 덱에서 가져온 카드에
/// 트릭 승리 표식(트로피)이 붙었다. 가져온 카드는 이긴 카드가 아니다.
///
/// 색을 나눠 쓴다. 전에는 전부 파란 테두리였는데, 카드 그림이 대부분
/// 파랑·보라 계열이라 거기 묻혀 눈에 띄지 않았다.
enum SkCardHighlight {
  none,

  /// 내가 손패에서 고른 카드. 주황.
  selected,

  /// 트릭을 이긴 카드. 노랑 + 트로피.
  winner,

  /// 능력으로 방금 가져온 카드(벤트). 초록 + 아래로 들어오는 화살표.
  ///
  /// 손패에 섞여 있는 상태에서 "어느 게 새로 온 카드인지" 만 알려 주면
  /// 되는 자리라, 승리 표식처럼 띄우거나 키우지 않는다.
  drawn,
}
